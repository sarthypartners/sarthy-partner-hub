if os.path.exists(domain_file):
    with open(domain_file) as f:
        domain = f.read().strip()
    if domain:
        with open(os.path.join(DIST, "CNAME"), "w") as f:
            f.write(domain + "\n")
        print("Custom domain set:", domain)

print("Built dist/index.html -", len(html), "chars,", len(docs), "documents,", len(queued), "queued")
