import json, os

ROOT = os.path.dirname(os.path.abspath(__file__))
CONTENT = os.path.join(ROOT, "content")
DIST = os.path.join(ROOT, "dist")

with open(os.path.join(CONTENT, "manifest.json")) as f:
    manifest = json.load(f)
with open(os.path.join(CONTENT, "queued.json")) as f:
    queued = json.load(f)
with open(os.path.join(CONTENT, "categories.json")) as f:
    cats = json.load(f)
with open(os.path.join(CONTENT, "changelog.json")) as f:
    changelog = json.load(f)

docs = []
for entry in manifest:
    with open(os.path.join(CONTENT, entry["content_file"])) as f:
        body = f.read()
    d = dict(entry)
    d["html"] = body
    docs.append(d)

